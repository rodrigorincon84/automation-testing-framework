from abc import abstractmethod

from .element import Element, UIAction, UIQuestion, UIShould


# ###############################################################################################################
# #########   Button element ####################################################################################
# ###############################################################################################################

class Button(Element):

    # Builders
    # #####################################################################
    @abstractmethod
    def build(self) -> "Button":
        ...

    # #####################################################################

    @abstractmethod
    def should_(self) -> "BtnShould":
        ...

    @abstractmethod
    def question(self) -> "BtnQuestion":
        ...

    @abstractmethod
    def action(self) -> "BtnAction":
        ...

# ###############################################################################################################
# #########   Button action #####################################################################################
# ###############################################################################################################


class BtnAction(UIAction):

    @abstractmethod
    def wait_until_process_action_finish(self):
        ...

    @abstractmethod
    def should_(self) -> "BtnShould":
        ...

    @abstractmethod
    def question(self) -> "BtnQuestion":
        ...

# ###############################################################################################################
# #########   Button question ###################################################################################
# ###############################################################################################################


class BtnQuestion(UIQuestion):
    ...

    @abstractmethod
    def should_(self) -> "BtnShould":
        ...

    @abstractmethod
    def action(self) -> "BtnAction":
        ...

# ###############################################################################################################
# #########   Button should #####################################################################################
# ###############################################################################################################


class BtnShould(UIShould):

    @abstractmethod
    def be_selected(self):
        ...

    @abstractmethod
    def question(self) -> "BtnQuestion":
        ...

    def action(self) -> "BtnAction":
        ...
